<?php

declare(strict_types=1);

/*
 * Generates src/<Api>/Types.php from spec/<api>-v<n>.yaml:
 *
 *     composer generate
 *
 * The library returns the API's objects as plain arrays (unknown fields kept,
 * so nothing breaks when Reeds adds one). This file gives those arrays types:
 * a PHPStan / Psalm array shape per schema, imported by the resource classes
 * (`@phpstan-import-type Delivery from Types`). IDEs and static analysis then
 * know every field.
 *
 * - Enums are plain `string`, because Reeds adds values inside a version (a new
 *   status). A single-value enum (an event's `type`) is its literal, so it
 *   still narrows.
 * - Shapes end in `...`: the API adds fields inside a version.
 *
 * The specs in spec/ are copies of sendx-api's openapi/*.yaml, taken by the
 * sync-spec workflow; never edit them or the generated files by hand.
 */

require __DIR__ . '/../vendor/autoload.php';

use Symfony\Component\Yaml\Yaml;

const APIS = [
    ['namespace' => 'Reeds\\Shipping', 'spec' => 'spec/shipping-v1.yaml', 'out' => 'src/Shipping/Types.php', 'title' => 'Shipping API'],
];

/** Schemas that are transport, not objects a caller handles. */
const SKIP = ['/Envelope$/', '/^Error$/', '/^ErrorCode$/', '/^OAuthError$/', '/^TokenRequest$/', '/^TokenResponse$/'];

$root = dirname(__DIR__);

foreach (APIS as $api) {
    $spec = Yaml::parseFile("{$root}/{$api['spec']}");
    $schemas = $spec['components']['schemas'] ?? [];
    $aliases = [];
    foreach ($schemas as $name => $schema) {
        if (array_filter(SKIP, static fn (string $re): bool => preg_match($re, $name) === 1) !== []) {
            continue;
        }
        $aliases[$name] = $schema;
    }
    $types = [];
    foreach ($aliases as $name => $schema) {
        $types[$name] = typeOf($schema, $schemas, $aliases);
    }
    // The list operations' query parameters, as <OperationId>Query.
    foreach ($spec['paths'] as $path => $item) {
        foreach ($item as $method => $operation) {
            if (!in_array($method, ['get', 'post', 'patch', 'put', 'delete'], true)) {
                continue;
            }
            $query = [];
            foreach ([...($item['parameters'] ?? []), ...($operation['parameters'] ?? [])] as $parameter) {
                $parameter = resolveParameter($parameter, $spec);
                if (($parameter['in'] ?? null) === 'query') {
                    $query[] = $parameter;
                }
            }
            if ($query === []) {
                continue;
            }
            $fields = [];
            foreach ($query as $parameter) {
                $fields[] = key_($parameter['name']) . (($parameter['required'] ?? false) ? '' : '?') . ': ' . typeOf($parameter['schema'] ?? [], $schemas, $aliases);
            }
            $types[ucfirst($operation['operationId']) . 'Query'] = 'array{' . implode(', ', [...$fields, '...']) . '}';
        }
    }

    $lines = [];
    foreach ($types as $name => $type) {
        $lines[] = " * @phpstan-type {$name} {$type}";
    }
    $namespace = $api['namespace'];
    $title = $api['title'];
    $file = <<<PHP
<?php

// Generated by scripts/generate.php from {$api['spec']}. Do not edit: run `composer generate`.

declare(strict_types=1);

namespace {$namespace};

/**
 * The {$title}'s objects, as the array shapes the library returns. Import one
 * into your own code with `@phpstan-import-type Delivery from \\{$namespace}\\Types`.
 *

PHP;
    $file .= implode("\n", $lines) . "\n */\nfinal class Types\n{\n    private function __construct()\n    {\n    }\n}\n";
    file_put_contents("{$root}/{$api['out']}", $file);
    fwrite(STDOUT, "{$api['spec']} -> {$api['out']} (" . count($types) . " types)\n");
}

/** @param array<string, mixed> $parameter */
function resolveParameter(array $parameter, array $spec): array
{
    if (isset($parameter['$ref'])) {
        $name = basename($parameter['$ref']);
        return $spec['components']['parameters'][$name] ?? [];
    }
    return $parameter;
}

function key_(string $name): string
{
    return preg_match('/^[A-Za-z_][A-Za-z0-9_]*$/', $name) === 1 ? $name : "'" . str_replace("'", "\\'", $name) . "'";
}

/**
 * @param array<string, mixed> $schema
 * @param array<string, mixed> $schemas every schema, to resolve references to skipped ones
 * @param array<string, mixed> $aliases the schemas that get an alias
 */
function typeOf(array $schema, array $schemas, array $aliases): string
{
    if (isset($schema['$ref'])) {
        $name = basename($schema['$ref']);
        return isset($aliases[$name]) ? $name : typeOf($schemas[$name] ?? [], $schemas, $aliases);
    }
    if (isset($schema['allOf'])) {
        return shape(merge($schema['allOf'], $schemas), $schemas, $aliases, nullable($schema));
    }
    foreach (['oneOf', 'anyOf'] as $keyword) {
        if (isset($schema[$keyword])) {
            $types = array_unique(array_map(static fn (array $s): string => typeOf($s, $schemas, $aliases), $schema[$keyword]));
            return withNull(implode('|', $types), nullable($schema));
        }
    }
    $types = (array) ($schema['type'] ?? []);
    $isNull = in_array('null', $types, true) || nullable($schema);
    $types = array_values(array_filter($types, static fn (string $t): bool => $t !== 'null'));
    if (isset($schema['enum']) && is_array($schema['enum'])) {
        $values = array_values(array_filter($schema['enum'], static fn ($v): bool => $v !== null));
        if (count($values) === 1 && is_string($values[0])) {
            return withNull("'" . str_replace("'", "\\'", $values[0]) . "'", $isNull);
        }
        // `available: true` on a quote, `false` when it isn't: literals, so the two narrow apart.
        if (count($values) === 1 && is_bool($values[0])) {
            return withNull($values[0] ? 'true' : 'false', $isNull);
        }
    }
    if ($types === [] && (isset($schema['properties']) || isset($schema['additionalProperties']))) {
        $types = ['object'];
    }
    if ($types === []) {
        // `type: 'null'` alone (one side of a oneOf) is null, not anything.
        return $isNull ? 'null' : 'mixed';
    }
    $parts = array_map(static function (string $type) use ($schema, $schemas, $aliases): string {
        return match ($type) {
            'string' => 'string',
            'integer' => 'int',
            'number' => 'float|int',
            'boolean' => 'bool',
            'array' => 'list<' . typeOf($schema['items'] ?? [], $schemas, $aliases) . '>',
            'object' => object($schema, $schemas, $aliases),
            default => 'mixed',
        };
    }, $types);
    return withNull(implode('|', array_unique($parts)), $isNull);
}

/** @param array<string, mixed> $schema */
function object(array $schema, array $schemas, array $aliases): string
{
    if (isset($schema['properties']) && $schema['properties'] !== []) {
        return shape($schema, $schemas, $aliases, false);
    }
    $additional = $schema['additionalProperties'] ?? null;
    if (is_array($additional)) {
        return 'array<string, ' . typeOf($additional, $schemas, $aliases) . '>';
    }
    return 'array<string, mixed>';
}

/** One object out of an allOf: the properties and required lists of every part. */
function merge(array $parts, array $schemas): array
{
    $merged = ['type' => 'object', 'properties' => [], 'required' => []];
    foreach ($parts as $part) {
        if (isset($part['$ref'])) {
            $part = $schemas[basename($part['$ref'])] ?? [];
            if (isset($part['allOf'])) {
                $part = merge($part['allOf'], $schemas);
            }
        }
        foreach ($part['properties'] ?? [] as $name => $property) {
            $merged['properties'][$name] = $property;
        }
        $merged['required'] = [...$merged['required'], ...($part['required'] ?? [])];
    }
    return $merged;
}

/** @param array<string, mixed> $schema */
function shape(array $schema, array $schemas, array $aliases, bool $isNull): string
{
    $required = $schema['required'] ?? [];
    $fields = [];
    foreach ($schema['properties'] ?? [] as $name => $property) {
        $fields[] = key_((string) $name) . (in_array($name, $required, true) ? '' : '?') . ': ' . typeOf($property, $schemas, $aliases);
    }
    $fields[] = '...';
    return withNull('array{' . implode(', ', $fields) . '}', $isNull);
}

/** @param array<string, mixed> $schema */
function nullable(array $schema): bool
{
    return ($schema['nullable'] ?? false) === true;
}

function withNull(string $type, bool $isNull): string
{
    return $isNull && !str_contains("|{$type}|", '|null|') ? "{$type}|null" : $type;
}
